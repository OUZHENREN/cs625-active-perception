#!/usr/bin/env python3
"""Publish the real-cell scene into MoveIt's planning scene.

Why this exists: Gazebo knows the tables, the slot fixture and the workpiece, and
MoveIt does not.  Without this the planner routes the arm straight through the
slot fixture, and a simulated run then proves nothing about the real cell.

The three collision bodies come from two already-authoritative sources:

    config/cs625_real_cell_scene.yaml    tables (measured boxes) + fixture/module poses
    runtime/environment/latest/model.json  only as a cross-check of the table boxes

The scene config is generated by ``scripts/build_sim_world.py`` from the measured
environment model, so nothing here restates a dimension that already exists.

Frames: the planning frame is ``world`` (the SRDF pins base_link to world with a
fixed virtual joint and sim_moveit.launch.py sets octomap_frame: world), so every
pose in the scene config is already in the frame MoveIt expects.

Usage:
    python3 scripts/apply_real_cell_scene.py --dry-run      # print, publish nothing
    python3 scripts/apply_real_cell_scene.py                # publish
    python3 scripts/apply_real_cell_scene.py --remove       # remove the bodies
"""

from __future__ import annotations

import argparse
import json
import math
import pathlib
import sys

import yaml

REPO = pathlib.Path(__file__).resolve().parent.parent
SCENE_CONFIG = REPO / "config" / "cs625_real_cell_scene.yaml"
MODEL_JSON = REPO / "runtime" / "environment" / "latest.json"
MESH_ROOT = REPO / "src" / "cs625_simulation" / "assets"
WORLD_FRAME = "world"


def load_scene(path: pathlib.Path = SCENE_CONFIG) -> dict:
    """Return the scene parameters (the file wraps them in ros__parameters)."""
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise SystemExit(f"{path} did not parse as a mapping")
    for value in raw.values():
        if isinstance(value, dict) and "ros__parameters" in value:
            return dict(value["ros__parameters"])
    raise SystemExit(f"{path} has no ros__parameters block")


def table_boxes(scene: dict) -> list[dict]:
    """One box per measured table, centred on its measured footprint."""
    boxes = []
    for name, table in (scene.get("tables") or {}).items():
        centre = table.get("box_centre")
        size = table.get("box_size")
        if not centre or not size:
            raise SystemExit(f"table {name} is missing box_centre/box_size")
        boxes.append({"name": name, "centre": [float(v) for v in centre],
                      "size": [float(v) for v in size]})
    return boxes


def rpy_to_quaternion(roll: float, pitch: float, yaw: float) -> tuple[float, float, float, float]:
    """SDF pose rpy (extrinsic x-y-z) to an xyzw quaternion."""
    cr, sr = math.cos(roll / 2.0), math.sin(roll / 2.0)
    cp, sp = math.cos(pitch / 2.0), math.sin(pitch / 2.0)
    cy, sy = math.cos(yaw / 2.0), math.sin(yaw / 2.0)
    return (
        sr * cp * cy - cr * sp * sy,
        cr * sp * cy + sr * cp * sy,
        cr * cp * sy - sr * sp * cy,
        cr * cp * cy + sr * sp * sy,
    )


def mesh_path(model_uri: str) -> pathlib.Path:
    """model://cs625_task/slot_fixture -> src/cs625_simulation/assets/.../meshes/*.stl"""
    parts = model_uri.split("://", 1)[-1].split("/")
    if len(parts) < 2:
        raise SystemExit(f"cannot resolve model uri {model_uri!r}")
    model_dir = MESH_ROOT.joinpath(*parts)
    meshes = sorted(model_dir.glob("meshes/*.stl")) or sorted(model_dir.glob("meshes/*.dae"))
    if not meshes:
        raise SystemExit(f"no mesh found under {model_dir}/meshes")
    # the collision mesh is the decimated one when both exist
    for candidate in meshes:
        if "collision" in candidate.name:
            return candidate
    return meshes[0]


def body_specs(scene: dict) -> list[dict]:
    """Everything that must exist in the planning scene, as plain dicts."""
    specs = []
    for box in table_boxes(scene):
        specs.append({"id": f"real_cell_{box['name']}", "kind": "box",
                      "frame": WORLD_FRAME,
                      "pose": {"xyz": box["centre"], "quat_xyzw": [0.0, 0.0, 0.0, 1.0]},
                      "size": box["size"]})
    for key, name in (("fixture", "slot_fixture"), ("module", "shielding_module")):
        entry = scene.get(key) or {}
        pose = entry.get("pose_world")
        if not pose:
            continue
        xyz = [float(v) for v in pose[:3]]
        quat = rpy_to_quaternion(*(float(v) for v in pose[3:6]))
        specs.append({"id": f"real_cell_{name}", "kind": "mesh",
                      "frame": WORLD_FRAME,
                      "pose": {"xyz": xyz, "quat_xyzw": list(quat)},
                      "mesh": str(mesh_path(str(entry.get("model_uri", ""))))})
    return specs


def cross_check_tables(scene: dict, model_json: pathlib.Path = MODEL_JSON) -> list[str]:
    """Compare the config's table boxes with the environment model, when present."""
    notes = []
    try:
        pointer = model_json if model_json.exists() else None
        if pointer is None:
            return ["environment model not built yet; table cross-check skipped"]
        target = json.loads(pointer.read_text(encoding="utf-8"))
        path = pathlib.Path(target.get("model", target) if isinstance(target, dict) else target)
        if not path.is_absolute():
            path = pointer.parent / path
        model = json.loads(pathlib.Path(path).read_text(encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001 - diagnostics must never block publishing
        return [f"environment model unreadable ({exc}); cross-check skipped"]
    for name, table in (scene.get("tables") or {}).items():
        measured = (model.get("tables") or {}).get(name)
        if not measured:
            notes.append(f"{name}: not present in the environment model")
            continue
        delta = abs(float(table["top_z"]) - float(measured.get("z", float("nan"))))
        notes.append(f"{name}: top_z config {table['top_z']:.4f} vs model "
                     f"{measured.get('z', float('nan')):.4f} (Δ {delta * 1000:.1f} mm)")
    return notes


def mesh_from_stl(path: pathlib.Path):
    """Binary STL -> shape_msgs/Mesh, reusing the loader of the P7 scene applier."""
    import importlib.util

    source = REPO / "src" / "cs625_bringup" / "scripts" / "apply_task_scene.py"
    spec = importlib.util.spec_from_file_location("apply_task_scene", source)
    module = importlib.util.module_from_spec(spec)
    sys.modules["apply_task_scene"] = module
    spec.loader.exec_module(module)
    return module.mesh_from_stl(path)


def publish(specs: list[dict], remove: bool = False) -> int:
    import rclpy
    from geometry_msgs.msg import Pose
    from moveit_msgs.msg import CollisionObject, PlanningScene
    from shape_msgs.msg import SolidPrimitive
    from rclpy.node import Node
    from rclpy.qos import DurabilityPolicy, QoSProfile

    rclpy.init()
    node = Node("apply_real_cell_scene")
    latched = QoSProfile(depth=1, durability=DurabilityPolicy.TRANSIENT_LOCAL)
    publisher = node.create_publisher(PlanningScene, "/planning_scene", latched)
    scene = PlanningScene()
    scene.is_diff = True
    for spec in specs:
        obj = CollisionObject()
        obj.header.frame_id = spec["frame"]
        obj.id = spec["id"]
        pose = Pose()
        pose.position.x, pose.position.y, pose.position.z = spec["pose"]["xyz"]
        (pose.orientation.x, pose.orientation.y,
         pose.orientation.z, pose.orientation.w) = spec["pose"]["quat_xyzw"]
        if remove:
            obj.operation = CollisionObject.REMOVE
        else:
            obj.operation = CollisionObject.ADD
            if spec["kind"] == "box":
                primitive = SolidPrimitive()
                primitive.type = SolidPrimitive.BOX
                primitive.dimensions = list(spec["size"])
                obj.primitives.append(primitive)
                obj.primitive_poses.append(pose)
            else:
                obj.meshes.append(mesh_from_stl(pathlib.Path(spec["mesh"])))
                obj.mesh_poses.append(pose)
        scene.world.collision_objects.append(obj)
    # the publisher needs a moment to match a latched subscriber
    for _ in range(20):
        publisher.publish(scene)
        rclpy.spin_once(node, timeout_sec=0.05)
    node.get_logger().info(
        f"{'removed' if remove else 'published'} {len(specs)} collision objects to "
        f"{WORLD_FRAME}")
    node.destroy_node()
    rclpy.shutdown()
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", default=str(SCENE_CONFIG))
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--remove", action="store_true")
    parser.add_argument("--include-module", action="store_true",
                        help="also publish the workpiece.  Off by default: the gripper "
                             "must touch it to grasp it, so a solid body there makes "
                             "every grasp approach infeasible.  The real cell attaches "
                             "it after the grasp (collision_object_publisher + touch_links).")
    parser.add_argument("--include-tables", action="store_true",
                        help="also publish the two measured table boxes.  Off by "
                             "default, matching the proven real-cell scene (only the "
                             "fixture plus the attached workpiece).  The measured table "
                             "height is centimetre-accurate, and a grasp pose that "
                             "clears the real table by 3 cm reports a false collision "
                             "against the box.")
    args = parser.parse_args()

    scene = load_scene(pathlib.Path(args.config))
    specs = body_specs(scene)
    if not args.include_module:
        specs = [spec for spec in specs if "shielding_module" not in spec["id"]]
    if not args.include_tables:
        specs = [spec for spec in specs if spec["kind"] != "box"]
    print(f"scene config : {args.config}")
    print(f"world frame  : {WORLD_FRAME}")
    for spec in specs:
        pose = spec["pose"]
        extra = spec.get("size") or spec.get("mesh")
        print(f"  {spec['id']:<28} {spec['kind']:<5} "
              f"xyz={[round(v, 4) for v in pose['xyz']]} {extra}")
    for note in cross_check_tables(scene):
        print(f"  cross-check: {note}")
    if args.dry_run:
        print("dry run: nothing published")
        return 0
    return publish(specs, remove=args.remove)


if __name__ == "__main__":
    sys.exit(main())
